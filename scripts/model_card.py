"""Stage 0, "meet your model": what goes in, what comes out, how good it is, where it fails.

    python scripts/model_card.py        # writes MODEL_CARD.md

Scores every transaction in data/transactions_sample.csv through the real service code
(Transaction -> FraudScorer -> SklearnModel) and compares the decisions with the labels.
"""
import csv
from collections import Counter
from pathlib import Path

from fraud_service.adapters.sklearn_model import SklearnModel
from fraud_service.domain.entities import Transaction
from fraud_service.service.scorer import FraudScorer

model = SklearnModel.load(Path("models/fraud_xgb_v3.joblib"))
scorer = FraudScorer(model=model, block_threshold=0.85)
fields = list(Transaction.model_fields)

rows = []
with open("data/transactions_sample.csv", newline="", encoding="utf-8") as f:
    for r in csv.DictReader(f):
        res = scorer.score(Transaction(**{k: r[k] for k in fields}))
        rows.append((int(r["is_fraud"]), res.probability, res.decision.value, r))

n = len(rows)
frauds = sum(y for y, *_ in rows)


def at(threshold: float) -> tuple[int, int, int, int]:
    tp = sum(1 for y, p, *_ in rows if p >= threshold and y == 1)
    fp = sum(1 for y, p, *_ in rows if p >= threshold and y == 0)
    fn = sum(1 for y, p, *_ in rows if p < threshold and y == 1)
    tn = n - tp - fp - fn
    return tp, fp, fn, tn


def auc() -> float:  # probability that a random fraud scores above a random legit payment
    pos = sorted(p for y, p, *_ in rows if y == 1)
    neg = sorted(p for y, p, *_ in rows if y == 0)
    wins, j = 0.0, 0
    for p in pos:
        while j < len(neg) and neg[j] < p:
            j += 1
        ties = sum(1 for q in neg[j:] if q == p)
        wins += j + 0.5 * ties
    return wins / (len(pos) * len(neg))


decisions = Counter(d for *_, d, _ in rows)
missed = sorted((r for r in rows if r[0] == 1), key=lambda r: r[1])[:5]

lines = [
    "# Model card · fraud_xgb " + model.model_version, "",
    "Generated by `python scripts/model_card.py` from the real service code.", "",
    "## What goes in, what comes out", "",
    "- **In:** one card transaction: amount in SAR, channel (pos, ecom, atm, transfer),",
    "  merchant category, customer id, timestamp with a timezone.",
    "- **Features the model sees** (`Transaction.to_features()`): `amount_log`, `channel`, `mcc`,",
    "  `hour_of_day` (UTC), `is_night` (UTC hour < 6). The customer id is *not* a feature.",
    "- **Model:** scikit-learn `HistGradientBoostingClassifier` behind a one-hot encoder.",
    "- **Out:** a fraud probability from 0 to 1, then a business decision:",
    "  `block` at 0.85 or more, `review` from 0.70, otherwise `allow`.", "",
    "## How good it is", "",
    f"- Data: {n:,} synthetic transactions, {frauds:,} of them fraud ({frauds / n:.1%}).",
    f"- **AUC: {auc():.3f}** (1.0 = every fraud scores above every legitimate payment; 0.5 = coin flip).",
    "", "| Threshold | Frauds caught | Frauds missed | False alarms (legit flagged) |", "|---|---|---|---|",
]
for t, name in [(0.85, "0.85 (block)"), (0.70, "0.70 (review or block)"), (0.50, "0.50 (for comparison)")]:
    tp, fp, fn, tn = at(t)
    lines.append(f"| {name} | {tp} of {frauds} ({tp / frauds:.0%}) | {fn} | {fp} |")
lines += [
    "", f"Decisions over all rows: {dict(decisions)}.", "",
    "**Accuracy misleads here.** A model that answers `allow` to everything is "
    f"{(n - frauds) / n:.1%} accurate and catches no fraud at all, so we read caught / missed / false alarms instead.",
    "", "## Where it fails", "",
    "- These numbers are measured on the same synthetic data the model was trained on, so they are",
    "  optimistic. A real evaluation needs a held-out, more recent period.",
    "- The thresholds are strict: most fraud lands below 0.85, so `block` is rare and most caught",
    "  fraud goes through `review`, a person.",
    "- Five frauds the model scored lowest (it was most sure they were fine):", "",
    "| transaction_id | amount_sar | channel | merchant_category | UTC hour | score |", "|---|---|---|---|---|---|",
]
for y, p, d, r in missed:
    lines.append(f"| {r['transaction_id']} | {r['amount_sar']} | {r['channel']} | {r['merchant_category']} "
                 f"| {r['timestamp'][11:13]} | {p:.4f} |")
lines += ["", "- It knows nothing about the customer's history (velocity, usual merchants, location),",
          "  which is where much real fraud shows up."]
Path("MODEL_CARD.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
